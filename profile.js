  // ---- State ----------------------------------------------------------------
  let box = null;
  let profile = {};
  let commDept = "gsa";   // which department's table is being edited
  let commDraft = null;   // working copy of the table
  let saveTimer = null;

  // ---- Helpers ---------------------------------------------------------------
  function deptTitle(id) {
    const d = DEPARTMENTS.find(x => x.id === id);
    return d ? d.title : id;
  }
  function getProfile(backup) {
    return (backup && backup.data && backup.data.profile) || {};
  }
  function splitName(full) {
    const parts = String(full || "").trim().split(/\s+/);
    if (!parts.length || !parts[0]) return { first: "", last: "" };
    return { first: parts[0], last: parts.slice(1).join(" ") };
  }
  function sessionEmail() {
    try { return (SupaClient.getSession() || {}).email || ""; } catch (e) { return ""; }
  }
  function photoData() {
    // Mirrors the app's account.profile?.profilePhoto (base64 data URL).
    return profile.profilePhoto || profile.photo || "";
  }
  function widgetState() {
    // Effective ordered list of VISIBLE widget ids.
    const order = (profile.homeWidgetOrder && profile.homeWidgetOrder.length)
      ? profile.homeWidgetOrder.slice() : DEFAULT_WIDGET_ORDER.slice();
    const off = new Set(profile.homeWidgetsOff || []);
    const known = new Set(HOME_WIDGETS.map(w => w.id));
    // Keep saved order but drop unknown / off ids; append new defaults.
    let visible = order.filter(id => known.has(id) && !off.has(id));
    for (const w of HOME_WIDGETS) {
      if (!visible.includes(w.id) && !off.has(w.id)) visible.push(w.id);
    }
    return { visible, off };
  }
  async function saveProfile(updates, immediate) {
    Object.assign(profile, updates);
    const write = () => SyncEngine.queueWrite({ type: "updateProfile", updates }).catch(e => {
      showError("Couldn't save: " + (e.message || e));
    });
    if (immediate) return write();
    // Debounce rapid field edits so typing doesn't spam the queue.
    clearTimeout(saveTimer);
    return new Promise(resolve => {
      saveTimer = setTimeout(() => write().then(resolve, resolve), 600);
    });
  }
  function tierLabel(t) {
    const lo = "$" + Number(t.minPrice).toFixed(2);
    return (t.maxPrice === null || t.maxPrice === undefined)
      ? lo + " and up" : lo + " – $" + Number(t.maxPrice).toFixed(2);
  }

