  function bindAccount() {
    const first = box.querySelector("#pf-first"), last = box.querySelector("#pf-last");
    const commitName = () => {
      const n = (first.value + " " + last.value).trim().replace(/\s+/g, " ");
      saveProfile({ name: n });
      const nameEl = box.querySelector(".pf-name");
      if (nameEl) nameEl.textContent = n || "Your name";
    };
    ["change", "blur"].forEach(ev => { first.addEventListener(ev, commitName); last.addEventListener(ev, commitName); });

    box.querySelector("#pf-username").addEventListener("change", (e) => {
      const v = e.target.value.trim();
      if (v && !/^[A-Za-z0-9_.]{3,20}$/.test(v)) {
        showError("Username must be 3–20 characters: letters, numbers, _ and .");
        e.target.value = profile.username || "";
        return;
      }
      saveProfile({ username: v });
    });

    box.querySelector("#pf-nick").addEventListener("change", (e) =>
      saveProfile({ nickname: e.target.value.trim() }));

    box.querySelector("#pf-dept").addEventListener("change", (e) => {
      saveProfile({ department: e.target.value }, true).then(() => {
        // Commission editor shows the current department's table by default.
        commDept = e.target.value;
        refreshCommissionSection();
        const sub = box.querySelector(".pf-identity-main .li-sub");
        if (sub) sub.textContent = deptTitle(e.target.value);
      });
    });

    const copyBtn = box.querySelector("#pf-username-copy");
    if (copyBtn) copyBtn.addEventListener("click", async () => {
      const u = "@" + (profile.username || "");
      try {
        await navigator.clipboard.writeText(u);
        copyBtn.textContent = "Copied ✓";
        setTimeout(() => { copyBtn.textContent = u; }, 1500);
      } catch (e) { showError("Couldn't copy"); }
    });

    box.querySelector("#pf-photo").addEventListener("change", (e) => {
      const f = e.target.files && e.target.files[0];
      if (!f) return;
      const img = new Image();
      const url = URL.createObjectURL(f);
      img.onload = () => {
        URL.revokeObjectURL(url);
        const size = 256;
        const canvas = document.createElement("canvas");
        canvas.width = size; canvas.height = size;
        const ctx = canvas.getContext("2d");
        const side = Math.min(img.width, img.height);
        ctx.drawImage(img, (img.width - side) / 2, (img.height - side) / 2, side, side, 0, 0, size, size);
        const dataUrl = canvas.toDataURL("image/jpeg", 0.85);
        saveProfile({ profilePhoto: dataUrl }, true).then(() => {
          const wrap = box.querySelector(".pf-photo-wrap");
          if (wrap) {
            const imgEl = document.createElement("img");
            imgEl.src = dataUrl; imgEl.className = "pf-avatar"; imgEl.alt = "Profile photo";
            const old = wrap.querySelector(".pf-avatar");
            if (old) old.replaceWith(imgEl);
          }
          // Refresh the header avatar too.
          if (window.updateSettingsAvatar) window.updateSettingsAvatar().catch(() => {});
        });
      };
      img.onerror = () => { URL.revokeObjectURL(url); showError("Couldn't read that image."); };
      img.src = url;
    });

    box.querySelector("#pf-signout").addEventListener("click", async () => {
      if (!confirm("Sign out of Micro Buddy on this device?")) return;
      try { await fetch("/logout"); } catch (e) {}
      location.reload();
    });
  }

